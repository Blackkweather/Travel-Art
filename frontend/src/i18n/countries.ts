/** The country's name in the reader's language; the English name is the value. */
export function countryLabel(name?: string | null): string {
  if (!name) return ''
  return getLocale() === 'fr' ? (COUNTRY_FR[name] ?? name) : name
}

/** Options for a country picker, ordered by what the reader actually sees. */
export function countryOptions(names: readonly string[]): { value: string; label: string }[] {
  const locale = getLocale()
  return names
    .map((value) => ({ value, label: countryLabel(value) }))
    .sort((a, b) => a.label.localeCompare(b.label, locale))
}
